-- The world: maps, NPCs and spawns, imported from the original server's Data folder by tools/world/import.py
-- (docs/original/maps-npcs.md). The game server reads these tables at start-up; they can be edited directly, and
-- re-importing replaces them. Like `defs`, this schema holds proprietary game data and is not part of the migrations.
CREATE SCHEMA world;

-- One row per map the game server runs (Map.ini [SET_ZONE_n] and the map file's size and blocked cells).
CREATE TABLE world.maps (
    id            smallint PRIMARY KEY,
    -- the map's side; positions must stay inside 0 <= x, z < size (CMap::IsSafePos)
    size          integer  NOT NULL CHECK (size > 0),
    -- 'F' field or 'D' dungeon
    map_type      char(1)  NOT NULL DEFAULT 'F',
    -- Map.ini CreateType as the original numbers it: 0 none, 1 S, 2 F, 3 P party instance, 4 G guild, 5 R guild ranking, 6 H guild house
    create_type   smallint NOT NULL DEFAULT 0 CHECK (create_type BETWEEN 0 AND 6),
    -- Map.ini WarType: 1 for P (nobody is an enemy there outside duels and guild wars, docs/original/pvp.md section 1), else 0
    war_type      smallint NOT NULL DEFAULT 0 CHECK (war_type BETWEEN 0 AND 1),
    -- one bit per unit square, least significant bit first: cells NPC guards may not walk into
    blocked       bytea    NOT NULL,
    -- where players come back to life; per faction when set (Light, Fury), otherwise the common one
    rebirth_map   smallint,
    rebirth_pos   real[],
    rebirth_light_map smallint,
    rebirth_light_pos real[],
    rebirth_fury_map  smallint,
    rebirth_fury_pos  real[],
    -- 0 none, 1 rain, 2 snow; chance in percent, power 1 to 3, durations in minutes
    weather_state smallint NOT NULL DEFAULT 0,
    weather_rate  smallint NOT NULL DEFAULT 0,
    weather_power smallint NOT NULL DEFAULT 0,
    weather_delay smallint NOT NULL DEFAULT 0,
    weather_none_delay smallint NOT NULL DEFAULT 0,
    -- party instance zones (create_type 3, docs/original/instances.md sections 1 and 2): CreateTime as (day, hour, hours) triples one
    -- after the other, NULL when the key is missing (always open); CreateMinUser, EnterMaxUser; ExpireTime in minutes
    create_time   smallint[],
    create_min_user integer NOT NULL DEFAULT 0,
    enter_max_user  integer NOT NULL DEFAULT 30,
    expire_time   integer  NOT NULL DEFAULT 0,
    -- the file the row came from
    source_file   text     NOT NULL
);

-- NPC definitions (NpcQuest.SData). type_id is the NPC's position in its type's list (CNpcData::GetNpc looks it up by index).
CREATE TABLE world.npcs (
    type          smallint NOT NULL CHECK (type BETWEEN 1 AND 13),
    type_id       smallint NOT NULL CHECK (type_id >= 1),
    name          text     NOT NULL,
    -- 0 Light, 1 Fury, 2 both (the file stores 1, 2, other)
    country       smallint NOT NULL CHECK (country BETWEEN 0 AND 2),
    -- the three u32 fields after the id, and the merchant's extra byte (meanings not identified)
    value_a       bigint   NOT NULL,
    value_b       bigint   NOT NULL,
    value_c       bigint   NOT NULL,
    merchant_byte smallint,
    PRIMARY KEY (type, type_id)
);

-- A merchant's goods (type 1), in the file's order.
CREATE TABLE world.npc_shop_items (
    npc_type_id   smallint NOT NULL,
    seq           smallint NOT NULL,
    item_type     smallint NOT NULL,
    item_type_id  smallint NOT NULL,
    PRIMARY KEY (npc_type_id, seq)
);

-- A gatekeeper's three destinations (type 2). The original adds 0.9 to y when loading; stored as in the file.
CREATE TABLE world.npc_gates (
    npc_type_id   smallint NOT NULL,
    seq           smallint NOT NULL CHECK (seq BETWEEN 0 AND 2),
    map           smallint NOT NULL,
    pos_x         real     NOT NULL,
    pos_y         real     NOT NULL,
    pos_z         real     NOT NULL,
    name          text     NOT NULL,
    cost          bigint   NOT NULL,
    PRIMARY KEY (npc_type_id, seq)
);

-- NPC placements of a map file. The NPC stands at position 0; guards (type 8) walk the others.
CREATE TABLE world.map_npcs (
    id            integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map           smallint NOT NULL,
    seq           integer  NOT NULL,
    type          smallint NOT NULL,
    type_id       smallint NOT NULL,
    UNIQUE (map, seq)
);

CREATE TABLE world.map_npc_positions (
    map_npc_id    integer  NOT NULL REFERENCES world.map_npcs (id) ON DELETE CASCADE,
    seq           smallint NOT NULL,
    pos_x         real     NOT NULL,
    pos_y         real     NOT NULL,
    pos_z         real     NOT NULL,
    -- in radians as in the file; the original turns it into degrees (-d * 57.29578, + 360 when negative)
    direction     real     NOT NULL,
    PRIMARY KEY (map_npc_id, seq)
);

-- Monster spawn areas of a map file: a box and the monsters it holds.
CREATE TABLE world.mob_areas (
    id            integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map           smallint NOT NULL,
    seq           integer  NOT NULL,
    x1 real NOT NULL, y1 real NOT NULL, z1 real NOT NULL,
    x2 real NOT NULL, y2 real NOT NULL, z2 real NOT NULL,
    UNIQUE (map, seq)
);

CREATE TABLE world.mob_area_mobs (
    mob_area_id   integer  NOT NULL REFERENCES world.mob_areas (id) ON DELETE CASCADE,
    seq           smallint NOT NULL,
    mob_id        integer  NOT NULL,
    count         integer  NOT NULL,
    PRIMARY KEY (mob_area_id, seq)
);

-- Portals of a map file (stMapPortal), in file order: the client names a portal by this order (seq).
CREATE TABLE world.map_portals (
    map           smallint NOT NULL,
    seq           smallint NOT NULL,
    pos_x real NOT NULL, pos_y real NOT NULL, pos_z real NOT NULL,
    -- 0 everyone, 1 Light, 2 Fury; above 1000 an instance zone portal's id
    country       integer  NOT NULL,
    -- both 0: no level limit
    level_min     integer  NOT NULL,
    level_max     integer  NOT NULL,
    to_map        integer  NOT NULL,
    to_x real NOT NULL, to_y real NOT NULL, to_z real NOT NULL,
    PRIMARY KEY (map, seq)
);

-- Bind areas of a map file (stMapBind), in file order: where players come back to life when the map has no rebirth point
-- (CMap::GetBindPos). Country 1 Light, 2 Fury, 0 or 3 both; boxes holds x1, y1, z1, x2, y2, z2 per box.
CREATE TABLE world.map_binds (
    map           smallint NOT NULL,
    seq           smallint NOT NULL,
    country       integer  NOT NULL,
    attr          integer  NOT NULL,
    boxes         real[]   NOT NULL CHECK (cardinality(boxes) % 6 = 0),
    PRIMARY KEY (map, seq)
);

-- Quests (NpcQuest.SData, docs/original/quest.md section 1). The id is the record's position: the original finds quest n at record n - 1.
-- The texts stay in the client; only the name is kept, for the logs.
CREATE TABLE world.quests (
    id                 smallint PRIMARY KEY CHECK (id >= 1),
    name               text     NOT NULL,
    level_min          integer  NOT NULL,
    level_max          integer  NOT NULL,
    -- by race: 0 human, 1 elf, 2 human or elf, 3 deatheater, 4 vail, 5 vail or deatheater, 6 or more anyone
    country            smallint NOT NULL,
    -- the lowest mode, 0 easy to 3 ultimate
    grow               smallint NOT NULL,
    -- not checked by the server
    sex                smallint[] NOT NULL CHECK (cardinality(sex) = 2),
    -- 1 for each class allowed, by job number
    jobs               smallint[] NOT NULL CHECK (cardinality(jobs) = 6),
    -- previous quests: one of those set must be finished with success (wPrevQuest, wHG, shVG)
    prev_quest         integer  NOT NULL,
    prev_quest_2       integer  NOT NULL,
    prev_quest_3       integer  NOT NULL,
    -- the unused fields, kept as in the file: byCG, byOG, byIG, byParty, byPartyJob, dwTickStartTerm, dwTickKeepTime
    unused             bigint[] NOT NULL,
    -- minutes before it may end (unused by the data), the time limit in minutes (0 none)
    time_min           bigint   NOT NULL,
    time_limit         bigint   NOT NULL,
    -- dwTickRecvCount: not 0 means repeatable (not kept as finished)
    repeat_count       bigint   NOT NULL,
    -- 0 any NPC (or the start NPC), 1 click the start NPC, 2 give the start item to it, 3 have the start item, 4 use the start item
    start_type         smallint NOT NULL,
    start_npc_type     smallint NOT NULL,
    start_npc_id       integer  NOT NULL,
    start_item_type    smallint NOT NULL,
    start_item_id      smallint NOT NULL,
    -- items given at the start: type, type id, count for each of three (type 0: none)
    start_items        smallint[] NOT NULL CHECK (cardinality(start_items) = 9),
    -- 0 talk to the end NPC, 1 bring the end items, 2 kill monsters, 3 kill players of the other faction
    end_type           smallint NOT NULL,
    end_npc_type       smallint NOT NULL,
    end_npc_id         integer  NOT NULL,
    -- items to bring: type, type id, count for each of three
    end_items          smallint[] NOT NULL CHECK (cardinality(end_items) = 9),
    pc_kill_count      smallint NOT NULL,
    -- monsters to kill: monster id and count, twice
    mob_kills          integer[] NOT NULL CHECK (cardinality(mob_kills) = 4),
    -- 1 always result 0; 0 the player's choice (result_user_select results) or by what was brought or killed
    result_type        smallint NOT NULL,
    result_user_select smallint NOT NULL
);

-- The three results of each quest (stQuestResult). need_mob_id and need_item_id are 1-based indexes into mob_kills and end_items.
CREATE TABLE world.quest_results (
    quest_id        smallint NOT NULL REFERENCES world.quests (id) ON DELETE CASCADE,
    seq             smallint NOT NULL CHECK (seq BETWEEN 0 AND 2),
    need_mob_id     integer  NOT NULL,
    need_mob_count  smallint NOT NULL,
    need_item_id    smallint NOT NULL,
    need_item_count smallint NOT NULL,
    -- dwNeedTime, wNeedHG, shNeedVG, byNeedOG: all 0 in the data, not used
    unused          bigint[] NOT NULL,
    exp             bigint   NOT NULL,
    money           bigint   NOT NULL,
    item_type       smallint NOT NULL,
    item_type_id    smallint NOT NULL,
    -- the quest the client's dialog goes on with
    next_quest      integer  NOT NULL,
    PRIMARY KEY (quest_id, seq)
);

CREATE INDEX map_npcs_map_idx ON world.map_npcs (map);
CREATE INDEX mob_areas_map_idx ON world.mob_areas (map);

-- The boxes' sets (Data/ItemCreate.ini, docs/original/item-origins.md section 5.1): each [ItemCreate_n] section's lines in file order,
-- a grade and a weight. Imported as written (a set given twice keeps its last section); the game server applies the original's rules
-- (sets 1 to 255, grades 0 to 1024, weights above 0, grades without items count as 0, a grade given again adds to its first line).
CREATE TABLE world.item_create (
    set_no        integer  NOT NULL,
    seq           integer  NOT NULL,
    grade         integer  NOT NULL,
    weight        integer  NOT NULL,
    PRIMARY KEY (set_no, seq)
);

-- Item -> quest links (NpcQuest.SData, docs/original/quest-drops.md section 1.3): per item that starts or ends quests, the quest ids in
-- file order. Imported as written; the game server keeps item types and type ids 1 to 255 and quest ids above 0.
CREATE TABLE world.item_quest_links (
    item_type     smallint   NOT NULL,
    item_type_id  smallint   NOT NULL,
    started       smallint[] NOT NULL,
    ended         smallint[] NOT NULL,
    PRIMARY KEY (item_type, item_type_id)
);

-- Data/SequenceItemCreate.ini (docs/original/quest-drops.md section 4.1) as GetPrivateProfileInt reads it, for groups 1 to the file's
-- COUNT: the SEQUENCE and GRADE_0..GRADE_9 (missing keys 0). Imported as read; the game server applies the rules (8 groups at most, a
-- group with SEQUENCE 0 turns all off).
CREATE TABLE world.sequence_groups (
    group_no      integer  PRIMARY KEY,
    sequence      bigint   NOT NULL,
    grades        integer[] NOT NULL CHECK (cardinality(grades) = 10)
);

-- Data/KillStatus.SData (docs/original/pvp-2.md section 8): per record a faction (0 light, 1 fury), the kills of that grade, the
-- file's index (not read by the original) and six bonuses (type, value). Imported as written, in file order; the game server
-- adds grade 0, keeps types 1 to 27 and lets each grade take the larger of its own and the lower grades' values.
CREATE TABLE world.kill_status (
    seq           integer   PRIMARY KEY,
    faction       smallint  NOT NULL,
    kills         bigint    NOT NULL,
    file_index    integer   NOT NULL,
    bonus_types   smallint[] NOT NULL,
    bonus_values  integer[] NOT NULL
);

-- Data/Obelisk.ini's obelisks (docs/original/obelisks.md section 1): per [zone_N] section's [Obelisk_K] line, in file order (`seq`
-- over the whole file), the map N, the number K, the position, the monsters for a neutral, light and fury owner and the base
-- country as the file numbers it (0 neutral, 1 light, 2 fury). Imported as written; the game server applies the original's rules
-- (maps that exist, ids in file order, monsters that count, positions on the map).
CREATE TABLE world.obelisks (
    seq           integer  PRIMARY KEY,
    map           integer  NOT NULL,
    number        integer  NOT NULL,
    pos_x         real     NOT NULL,
    pos_y         real     NOT NULL,
    pos_z         real     NOT NULL,
    mob_neutral   integer  NOT NULL,
    mob_light     integer  NOT NULL,
    mob_fury      integer  NOT NULL,
    country       integer  NOT NULL
);

-- Each obelisk's [Mob] lines (its guard groups), in file order: the centre, the radius, the monsters for a neutral, light and
-- fury owner and how many.
CREATE TABLE world.obelisk_guards (
    obelisk_seq   integer  NOT NULL REFERENCES world.obelisks (seq),
    seq           integer  NOT NULL,
    pos_x         real     NOT NULL,
    pos_y         real     NOT NULL,
    pos_z         real     NOT NULL,
    radius        real     NOT NULL,
    mob_neutral   integer  NOT NULL,
    mob_light     integer  NOT NULL,
    mob_fury      integer  NOT NULL,
    count         integer  NOT NULL,
    PRIMARY KEY (obelisk_seq, seq)
);

-- Data/Obelisk.ini's boss groups (docs/original/obelisks.md sections 11.1 and 11.3): per [bothmob_n, (map, stages, respawn, (pmap,
-- portal))] line, in file order (`seq`), the number n, the map, the stages (cut to 15), the respawn time in seconds, the portal it
-- opens (its map and id), the boss's spot and one monster per stage. A [RandomRespawn] line makes the group random: min and max
-- minutes and three spots (nine values); NULL for a fixed group. Imported as written; the game server applies the original's rules
-- (maps that exist, monsters that count, a portal id from 1001 that the portal's map has).
CREATE TABLE world.boss_groups (
    seq           integer   PRIMARY KEY,
    number        integer   NOT NULL,
    map           integer   NOT NULL,
    stages        integer   NOT NULL,
    respawn_secs  integer   NOT NULL,
    portal_map    integer   NOT NULL,
    portal_id     integer   NOT NULL,
    pos_x         real      NOT NULL,
    pos_y         real      NOT NULL,
    pos_z         real      NOT NULL,
    mobs          integer[] NOT NULL,
    random_min    integer,
    random_max    integer,
    random_spots  real[]
);

-- Each boss group's [Mob] lines (its follower groups), in file order: the centre, the radius, one monster per stage and one more
-- (the chest monster, which comes when the last stage falls; 0 = none) and how many (cut to 16).
CREATE TABLE world.boss_followers (
    group_seq     integer   NOT NULL REFERENCES world.boss_groups (seq),
    seq           integer   NOT NULL,
    pos_x         real      NOT NULL,
    pos_y         real      NOT NULL,
    pos_z         real      NOT NULL,
    radius        real      NOT NULL,
    mobs          integer[] NOT NULL,
    count         integer   NOT NULL,
    PRIMARY KEY (group_seq, seq)
);

-- Data/mob_ai.ini's state machines (docs/original/scripted-mobs.md section 2): per line with a number of 10 and up, the number, the
-- path as written, and the four files the original reads (<path>.alo, .afs, .ai, .ah), as they are (code page 949 decoded). The game
-- server parses them at start-up.
CREATE TABLE world.mob_ai (
    ai            smallint PRIMARY KEY,
    path          text     NOT NULL,
    alo           text     NOT NULL,
    afs           text     NOT NULL,
    ai_text       text     NOT NULL,
    ah            text     NOT NULL
);

-- Data/kr_string.DB, the lines the state machines say (section 2): the id, the text as the file has it (bytes, without the line end),
-- and an English line the new server sends instead when it is set (section 12, deviation 1).
CREATE TABLE world.ai_strings (
    id            integer  PRIMARY KEY,
    text          bytea    NOT NULL,
    english       text
);

-- Data/Lua/<ai>.lua, the scripts of the monsters with AI 100 and up (docs/original/instances.md section 9): the number and the file's
-- bytes as they are (Lua 5.1 source, comments in code page 949). The game server runs them per monster.
CREATE TABLE world.mob_lua (
    ai            smallint PRIMARY KEY,
    source        bytea    NOT NULL
);

-- Data/GuildHouse.ini (docs/original/guild-house.md section 2), with the original's built-in values for keys the file lacks. One
-- row: the house's price and upkeep, and the rate lists by NPC level (index 0 = level 0).
CREATE TABLE world.guild_house (
    id            smallint PRIMARY KEY CHECK (id = 1),
    buy_money     integer  NOT NULL,
    keep_etin     integer  NOT NULL,
    gate_rates    float8[] NOT NULL,
    shop_rates    float8[] NOT NULL,
    potion_rates  float8[] NOT NULL,
    repair_rates  float8[] NOT NULL,
    mix_rates     float8[] NOT NULL,
    mix_bonus     integer[] NOT NULL,
    bank_slots    integer[] NOT NULL
);

-- Per house NPC key (2 gatekeeper, 3 blacksmith, 6 warehouse, shop type << 8 | 1 a merchant): the upkeep and the upgrade cost of
-- levels 1 and up (index 0 = level 1; a level past the list costs nothing and cannot be bought).
CREATE TABLE world.guild_house_npcs (
    npc_key       integer  PRIMARY KEY,
    keep_etin     integer[] NOT NULL,
    upgrade_etin  integer[] NOT NULL
);

-- NpcLevel_Light / NpcLevel_Dark: the NPC (type id) each level 1 to 3 of a kind unlocks, per country (0 Light, 1 Fury); kinds 0
-- gatekeeper, 1 weapons, 2 armour, 3 general goods.
CREATE TABLE world.guild_house_levels (
    country       smallint NOT NULL,
    kind          smallint NOT NULL,
    level         smallint NOT NULL,
    npc_type_id   integer  NOT NULL,
    PRIMARY KEY (country, kind, level)
);
