-- Data editing (docs/plans/done/data-editing.md section 3): every change the operator makes to the game's data (monster drops and stats,
-- item grades, spawns, obelisks, boss groups, portals) with its history, so that edits survive a fresh import of the original files
-- (`data-editor apply` writes them back), can be reviewed and undone, and can be exported and imported as one file. The schema is
-- `edits`, apart from `defs` and `world`, which the loaders replace; nothing here is touched by them. Every statement is guarded
-- (IF NOT EXISTS) because the tests of other binaries run all migrations again inside throwaway schemas of the same database.
CREATE SCHEMA IF NOT EXISTS edits;

-- One per Apply (or Undo, or Import): who, when, why. `undoes`/`undone_by` link a change set to the Undo that reverses it.
CREATE TABLE IF NOT EXISTS edits.change_sets (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    made_at     timestamptz NOT NULL DEFAULT now(),
    -- the name typed on the page, or 'cli'
    made_by     text NOT NULL,
    message     text NOT NULL CHECK (message <> ''),
    undoes      integer REFERENCES edits.change_sets (id),
    undone_by   integer REFERENCES edits.change_sets (id)
);

-- The edits now in force on existing rows: per target, row key and field, the value and the value before any edit. Keys are the
-- registry's text keys ('2/57'), values JSON (numbers, arrays of numbers).
CREATE TABLE IF NOT EXISTS edits.fields (
    target      text NOT NULL,
    key         text NOT NULL,
    field       text NOT NULL,
    value       jsonb NOT NULL,
    -- NULL for a field of a row the edits added
    original    jsonb,
    -- the last change set that set it
    change_set  integer NOT NULL REFERENCES edits.change_sets (id),
    PRIMARY KEY (target, key, field)
);

-- Rows the edits added (their fields are in edits.fields) or removed (`original` holds the row as it was, its child rows and their
-- edits included, as the registry's snapshot JSON).
CREATE TABLE IF NOT EXISTS edits.rows (
    target      text NOT NULL,
    key         text NOT NULL,
    action      text NOT NULL CHECK (action IN ('add', 'remove')),
    original    jsonb,
    change_set  integer NOT NULL REFERENCES edits.change_sets (id),
    PRIMARY KEY (target, key)
);

-- Every change of every change set, in order: the history, and what Undo reverses. `before` is the value in force before the change,
-- `after` the value after it (for a row added, removed or restored: the row's fields or its snapshot).
CREATE TABLE IF NOT EXISTS edits.log (
    change_set  integer NOT NULL REFERENCES edits.change_sets (id),
    seq         integer NOT NULL,
    target      text NOT NULL,
    key         text NOT NULL,
    -- NULL for a row added, removed or restored
    field       text,
    action      text NOT NULL CHECK (action IN ('set', 'unset', 'add', 'remove', 'restore')),
    before      jsonb,
    after       jsonb,
    PRIMARY KEY (change_set, seq)
);

-- Changes made on the page and not applied yet; one draft, shared by everyone using the editor. `value` is the new value of a field
-- (set), the fields of a new row (add) or nothing.
CREATE TABLE IF NOT EXISTS edits.draft (
    seq         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target      text NOT NULL,
    key         text NOT NULL,
    field       text,
    action      text NOT NULL CHECK (action IN ('set', 'unset', 'add', 'remove')),
    value       jsonb,
    made_by     text NOT NULL,
    made_at     timestamptz NOT NULL DEFAULT now()
);

-- The optional background picture of a map and the world rectangle it shows: the picture's left edge is x1, right x2, top z1, bottom
-- z2 (a flipped axis is x1 > x2 or z1 > z2). Without a row the page draws the grid alone, z upward.
CREATE TABLE IF NOT EXISTS edits.map_images (
    map          smallint PRIMARY KEY,
    content_type text NOT NULL CHECK (content_type IN ('image/png', 'image/jpeg')),
    image        bytea NOT NULL,
    x1 real NOT NULL, z1 real NOT NULL, x2 real NOT NULL, z2 real NOT NULL,
    -- where it came from ('upload', or the client file's name)
    source       text NOT NULL,
    added_at     timestamptz NOT NULL DEFAULT now()
);

-- A name per map for the page (the server has none: map names live in the client). Not a change set: it changes nothing in the game.
CREATE TABLE IF NOT EXISTS edits.map_names (
    map          smallint PRIMARY KEY,
    name         text NOT NULL
);
