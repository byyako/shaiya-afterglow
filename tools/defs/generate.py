#!/usr/bin/env python3
"""Generate the Postgres schema and the per-table SQL Server export queries for PS_GameDefs.

usage: generate.py <PS_GameDefs.columns.txt> <schema.sql out> <queries.tsv out>

The column list comes from docs/original/db (format: table|ordinal|column|type|nullability|identity|default|rows).
Text columns are exported as hex so the character set is decided on our side, not by
SQL Server's collation. queries.tsv has one line per table: <postgres table>\t<select statement>.
"""
import re
import sys
from collections import OrderedDict

# SQL Server table -> table name in the Postgres schema `defs`
TABLES = OrderedDict([
    ("Items", "items"),
    ("Mobs", "mobs"),
    ("MobItems", "mob_items"),
    ("Skills", "skills"),
    ("ExpDefs", "exp_defs"),
    ("StatusDefs", "status_defs"),
    ("BaseItemsDefs", "base_items_defs"),
    ("ProductList", "product_list"),
])
PRIMARY_KEYS = {"items": ["itemid"], "mobs": ["mobid"], "product_list": ["productcode"]}
INDEXES = {
    "items": [["type", "typeid"]],
    "mob_items": [["mobid"]],
    "skills": [["skillid", "skilllevel"]],
}
PG_TYPES = {"tinyint": "smallint", "smallint": "smallint", "int": "integer", "datetime": "timestamp"}


def export_expression(name, base):
    if base == "varchar":
        return f"CONVERT(varchar(max), CAST([{name}] AS varbinary(max)), 2)"
    if base == "datetime":
        return f"CONVERT(varchar(23), [{name}], 121)"
    return f"[{name}]"


def main():
    columns_file, schema_out, queries_out = sys.argv[1:4]
    columns = OrderedDict((t, []) for t in TABLES)
    for line in open(columns_file):
        parts = line.rstrip("\n").split("|")
        if len(parts) >= 8 and parts[0] in columns:
            columns[parts[0]].append((int(parts[1]), parts[2], re.sub(r"\(.*\)", "", parts[3]), parts[4] == "NULL"))

    ddl = ["-- Generated by tools/defs/generate.py from the PS_GameDefs column list. Do not edit by hand.",
           "-- Static game definitions restored from the original database. Column names are the originals, lowercased.",
           "CREATE SCHEMA IF NOT EXISTS defs;", ""]
    queries = []
    for table, pg in TABLES.items():
        fields = sorted(columns[table])
        lines = [f"    {name.lower()} {'text' if base == 'varchar' else PG_TYPES[base]}{'' if nullable else ' NOT NULL'}"
                 for _, name, base, nullable in fields]
        if pg in PRIMARY_KEYS:
            lines.append(f"    PRIMARY KEY ({', '.join(PRIMARY_KEYS[pg])})")
        ddl.append(f"CREATE TABLE defs.{pg} (\n" + ",\n".join(lines) + "\n);")
        for n, index in enumerate(INDEXES.get(pg, []), 1):
            ddl.append(f"CREATE INDEX {pg}_idx{n} ON defs.{pg} ({', '.join(index)});")
        ddl.append("")
        select = ", ".join(export_expression(name, base) for _, name, base, _ in fields)
        queries.append(f"{pg}\tSELECT {select} FROM [{table}] ORDER BY [{fields[0][1]}]")
    open(schema_out, "w").write("\n".join(ddl))
    open(queries_out, "w").write("\n".join(queries) + "\n")


if __name__ == "__main__":
    main()
